#!/usr/bin/env python3
"""Generate prompt/decisions-index.md (SD index) and the single-file prompt prompt/SKILL.md from the maintained sources.

单文件版 = 入口 SKILL.md + 规则总纲 + 排版规则总表 + 内容校对核心规则 + 经验与教训 + 长期决策索引（2026-10-23 方案 A）。
"""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCES = ('SKILL.md', 'prompt/portable-instruction.md', 'prompt/layout-checklist.md', 'prompt/content-core.md',
           'prompt/lessons.md', 'prompt/decisions-index.md')
INDEX = ROOT / 'prompt/decisions-index.md'
TARGET = ROOT / 'prompt/SKILL.md'


def render_index():
    import re
    sd = (ROOT / 'prompt/standing-decisions.md').read_text(encoding='utf-8')
    rows = []
    for line in sd.splitlines():
        m = re.match(r'^##\s+(SD-\d+)\s*[　 ]\s*(.+?)\s*$', line)
        if m:
            rows.append((int(m.group(1)[3:]), m.group(1), m.group(2).replace('|', '｜')))
    rows.sort()
    out = ['<!-- Generated by tools/export_prompt.py from prompt/standing-decisions.md; do not edit. -->',
           '# 长期决策索引（SD 编号 → 标题）', '',
           '> 现行口径一律以《规则总纲》《排版规则总表》《内容校对核心规则》为准；本索引只用来按编号查来历（全文在 standing-decisions.md）。标题后〔……〕里写了被哪条取代的，已不再执行。', '',
           '| 编号 | 标题（日期 / 状态） |', '|---|---|']
    out += ['| %s | %s |' % (k, t) for _, k, t in rows]
    return '\n'.join(out) + '\n'


def render():
    chunks = ['<!-- Generated by tools/export_prompt.py; do not edit. -->\n']
    for relative in SOURCES:
        text = (ROOT / relative).read_text(encoding='utf-8')
        if relative == 'SKILL.md':
            text = text.split('---', 2)[-1].strip().replace('(prompt/', '(')
        chunks.append('<!-- Source: ' + relative + ' -->\n\n' + text.strip() + '\n')
    return '\n---\n\n'.join(chunks)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    idx = render_index()
    if args.check:
        if not INDEX.is_file() or INDEX.read_text(encoding='utf-8') != idx:
            raise SystemExit('Decisions index is stale; run python3 tools/export_prompt.py')
        expected = render()
        if not TARGET.is_file() or TARGET.read_text(encoding='utf-8') != expected:
            raise SystemExit('Prompt is stale; run python3 tools/export_prompt.py')
        print('Prompt matches maintained sources')
    else:
        INDEX.write_text(idx, encoding='utf-8')
        TARGET.write_text(render(), encoding='utf-8')
        print('Generated prompt/decisions-index.md and prompt/SKILL.md')


if __name__ == '__main__':
    main()
